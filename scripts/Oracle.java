import java.io.File;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Objects;
import java.util.TimeZone;

import org.HdrHistogram.EncodableHistogram;
import org.HdrHistogram.Histogram;
import org.HdrHistogram.HistogramLogReader;
import org.HdrHistogram.HistogramLogWriter;
import org.HdrHistogram.HistogramIterationValue;

/** Generates synthetic logs and independently reads MoonHlog's output. */
public final class Oracle {
    private static final long START_MS = 1_700_000_000_000L;
    private static final long MAX_VALUE = 3_600_000_000L;
    private static final int SIGNIFICANT_DIGITS = 3;

    private static Histogram newHistogram() {
        return new Histogram(1, MAX_VALUE, SIGNIFICANT_DIGITS);
    }

    private static void writeInterval(
            HistogramLogWriter writer, String tag, double startSeconds,
            long ordinaryCount, long ordinaryValue, long tailCount, long tailValue) {
        Histogram histogram = newHistogram();
        histogram.setTag(tag);
        histogram.recordValueWithCount(ordinaryValue, ordinaryCount);
        if (tailCount > 0) {
            histogram.recordValueWithCount(tailValue, tailCount);
        }
        writer.outputIntervalHistogram(startSeconds, startSeconds + 1, histogram);
    }

    private static void generate(Path directory, boolean candidate) throws Exception {
        Files.createDirectories(directory);
        String fileName = candidate ? "candidate.hlog" : "baseline.hlog";
        HistogramLogWriter writer = new HistogramLogWriter(directory.resolve(fileName).toFile());
        try {
            writer.outputLogFormatVersion();
            writer.outputComment("Synthetic latencies in nanoseconds generated by scripts/Oracle.java");
            writer.outputStartTime(START_MS);
            double startSeconds = 0.25;
            if (!candidate) {
                writer.outputBaseTime(START_MS - 10_000);
                startSeconds += 10.0;
            }
            writer.outputLegend();
            writeInterval(writer, "read", startSeconds,
                    candidate ? 985 : 990, 10_000, candidate ? 15 : 10, 12_000);
            writeInterval(writer, "read", startSeconds + 1,
                    candidate ? 75 : 99, 10_000, candidate ? 25 : 1,
                    candidate ? 180_000 : 20_000);
            writeInterval(writer, "write", startSeconds + 2, 30, 75_000, 0, 0);
        } finally {
            writer.close();
        }
    }

    private static Histogram asIntegerHistogram(EncodableHistogram interval) {
        if (interval instanceof Histogram) {
            return (Histogram) interval;
        }
        throw new IllegalArgumentException("Expected an integer histogram");
    }

    private static void summary(File file, String tag, double from, double until) throws Exception {
        Histogram aggregate = new Histogram(SIGNIFICANT_DIGITS);
        try (HistogramLogReader reader = new HistogramLogReader(file)) {
            EncodableHistogram interval;
            while ((interval = reader.nextIntervalHistogram()) != null) {
                double relativeStart = interval.getStartTimeStamp() / 1000.0 - reader.getStartTimeSec();
                if ((tag == null || Objects.equals(tag, interval.getTag()))
                        && relativeStart >= from && relativeStart < until) {
                    aggregate.add(asIntegerHistogram(interval));
                }
            }
        }
        System.out.printf(
                "{\"samples\":%d,\"p50\":%d,\"p95\":%d,\"p99\":%d,\"p999\":%d}%n",
                aggregate.getTotalCount(), aggregate.getValueAtPercentile(50),
                aggregate.getValueAtPercentile(95), aggregate.getValueAtPercentile(99),
                aggregate.getValueAtPercentile(99.9));
    }

    private static void intervals(File file) throws Exception {
        try (HistogramLogReader reader = new HistogramLogReader(file)) {
            EncodableHistogram interval;
            while ((interval = reader.nextIntervalHistogram()) != null) {
                Histogram histogram = asIntegerHistogram(interval);
                System.out.printf("%s\t%d\t%d\t%d\t",
                        histogram.getTag(), histogram.getStartTimeStamp(),
                        histogram.getEndTimeStamp(), histogram.getTotalCount());
                for (HistogramIterationValue bucket : histogram.recordedValues()) {
                    System.out.printf("%d=%d,",
                            bucket.getValueIteratedTo(), bucket.getCountAtValueIteratedTo());
                }
                System.out.println();
            }
        }
    }

    public static void main(String[] args) throws Exception {
        switch (args[0]) {
            case "generate":
                TimeZone.setDefault(TimeZone.getTimeZone("UTC"));
                Path directory = Path.of(args[1]);
                generate(directory, false);
                generate(directory, true);
                break;
            case "summary":
                summary(new File(args[1]), args.length > 2 ? args[2] : null,
                        args.length > 3 ? Double.parseDouble(args[3]) : Double.NEGATIVE_INFINITY,
                        args.length > 4 ? Double.parseDouble(args[4]) : Double.POSITIVE_INFINITY);
                break;
            case "intervals":
                intervals(new File(args[1]));
                break;
            default:
                throw new IllegalArgumentException("Expected generate, summary, or intervals");
        }
    }
}
